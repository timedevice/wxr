"""gen_dcomp_iids.py - GUID constants DCIID_<Name> for dcomp.dll: public interfaces are read from the mingw dcomp headers, private ones come from wine-uwp's reading of dcomp.pdb."""
import re, sys, os
inc = sys.argv[2] if len(sys.argv) > 2 else '/usr/share/mingw-w64/include'
names = {}
for f in ('dcomp.h', 'dcompanimation.h'):
    t = open(os.path.join(inc, f)).read()
    for m in re.finditer(r'DECLARE_INTERFACE_IID_\((IDComposition\w+)\s*,\s*\w+\s*,\s*"([0-9a-fA-F-]{36})"', t): names[m.group(1)[len('IDComposition'):]] = m.group(2)
names.setdefault('Device3', '0987cb06-f916-48bf-8d35-ce7641781bd9')
names['DesktopDevice'] = names.get('DesktopDevice', '5f4633fe-1e08-4cb8-8c75-ce24333f5602')
extra = {  # no public header
 'Animation': 'cbfd91d9-51b2-45e4-b3de-d19ccfb863c5',
 'Visual3': '2775f462-b6c1-4015-b0be-b3e7d6a4976d', 'InteropVisual': 'fe93b735-e574-4a5d-a21a-f705c21945fa', 'InteropDev': 'd14b6158-c3fa-4bce-9c1f-b61d8665eab0', 'InteropDev2': 'e7894c70-af56-4f52-b382-4b3cd263dc6f',
 'Priv2nd': '735081dc-5e24-45da-a38f-e32cc349a9a0', 'Priv1': '7bd36c9a-56ee-4fdd-ac4e-76bbd16ec8e4', 'Priv2': '48ea31ad-7fcd-4076-a79c-90cc4b852c9b', 'Priv3': '7a38b2bd-cec8-4eeb-830f-d8d07aedebc3',
 'Priv4': '9cbd9312-070d-4588-9bf3-bbf528cf3e84', 'Priv5': '509eab63-6a73-4493-b7fe-80006df879c2', 'Priv6': 'ae47e78a-7910-4425-a482-a05b758adce9', 'DeviceInternal': '6b556968-2d25-11e2-99f6-8bc36088709b',
 'Partner': '0e779a72-3f2a-502d-a7a9-bf99988cfe4d', 'DeviceDebug': 'a1a3c64a-224f-4a81-9773-4f03a89d3c6c', 'RefuseMica': '0d8fb190-f122-5b8d-9fdd-543b0d8eb7f3', 'RefusePointer': '36af3eb2-0371-49d7-9bb8-9c9414a9229c'}
names.update(extra)
def lit(g):
    p = g.split('-'); return '{0x%s,0x%s,0x%s,{0x%s,0x%s,0x%s,0x%s,0x%s,0x%s,0x%s,0x%s}}' % (p[0], p[1], p[2], p[3][:2], p[3][2:], p[4][0:2], p[4][2:4], p[4][4:6], p[4][6:8], p[4][8:10], p[4][10:12])
out = sys.argv[1]
c = ['/* generated by gen_dcomp_iids.py */', '#include <windows.h>']; h = ['/* generated */', '#pragma once', '#include <windows.h>']
for n in sorted(names): c.append('const GUID DCIID_%s = %s;' % (n, lit(names[n]))); h.append('extern const GUID DCIID_%s;' % n)
open(os.path.join(out, 'dcomp_iids.c'), 'w').write('\n'.join(c) + '\n'); open(os.path.join(out, 'dcomp_iids.h'), 'w').write('\n'.join(h) + '\n')
print(len(names), 'iids')
